def capabilities(role: str) -> str:
    admin = RANK.get(role, 1) >= RANK["admin"]
    lines = [
        "### Чем могу помочь",
        "",
        "**Спросить про данные**",
        "",
        "- что просрочено, что оплатить сегодня, завтра или на неделе",
        "- сколько оплатили и сколько должны за любой период, по отделам, людям, платежам и валютам",
        "- средний чек, самый дорогой платёж, сколько оплат с опозданием",
        "- всё в рублях по курсу ЦБ, бюджет: план, факт и остаток",
        "- история конкретного платежа: кто, когда и сколько оплатил, есть ли чек",
        "",
        "**Спросить про продукт**",
        "",
        "- как отметить оплату и приложить чек, выгрузить CSV, подключить Telegram, почту или вебхук",
        "- как работают напоминания, роли и права, как сменить пароль",
        "",
        "**Сделать** (только после вашего «Подтвердить»)",
        "",
        "- отметить счёт оплаченным или вернуть в неоплаченные",
    ]
    if admin:
        lines += [
            "- создать, изменить или архивировать регулярный платёж",
            "- показать людей отдела и поискать в логах",
        ]
    else:
        lines += ["", "Шаблоны, люди и логи — у админа отдела."]
    return "\n".join(lines)


def topic_key(raw: str) -> str | None:
    text = fold(raw or "").strip()
    if text in TOPICS:
        return text
    words = {stem(token) for token in tokens(text)}
    best, score = None, 0
    for key, (_title, _role, _body, needles) in TOPICS.items():
        hits = 0
        for needle in needles:
            if " " in needle:
                hits += 2 if needle in text else 0
            elif any(word.startswith(needle) or needle.startswith(word) and len(word) >= 4 for word in words):
                hits += 1
        if hits > score:
            best, score = key, hits
    return best


def help_text(topic: str, role: str) -> str:
    key = topic_key(topic)
    if key is None or key == "assistant":
        return capabilities(role)
    title, minimum, body, _needles = TOPICS[key]
    note = ""
    if RANK.get(role, 1) < RANK[minimum]:
        note = "\n\nЭти действия выполняет админ отдела или владелец. Смотреть данные вы можете."
    return f"### {title}\n\n{body}{note}"


def topics_index() -> str:
    return ", ".join(TOPICS)
