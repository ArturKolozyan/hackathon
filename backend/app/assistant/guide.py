def capabilities(role: str) -> str:
    admin = RANK.get(role, 1) >= RANK["admin"]
    lines = [
        "### Чем могу помочь",
        "",
        "**Спросить**",
        "",
        "- что горит на этой неделе и что просрочено",
        "- сколько к оплате по валютам и что будет в ближайшие дни",
        "- сколько потратили за месяц, статистика по месяцам и по отделам",
        "- бюджет: план, факт и остаток",
        "- история платежа, кто ответственный, что висит на человеке",
        "- как пользоваться разделами: выгрузка CSV, Telegram, напоминания",
        "",
        "**Сделать** (после вашего «Подтвердить»)",
        "",
        "- отметить период оплаченным или вернуть в неоплаченные",
    ]
    if admin:
        lines += [
            "- создать, изменить или архивировать регулярный платёж",
            "- показать людей отдела и их нагрузку",
        ]
    else:
        lines += ["", "Создавать и менять шаблоны, смотреть список людей может админ отдела."]
    return "\n".join(lines)


def topic_key(raw: str) -> str | None:
    text = (raw or "").casefold().replace("ё", "е").strip()
    if text in TOPICS:
        return text
    for needle, key in ALIASES.items():
        if needle in text:
            return key
    return None


def help_text(topic: str, role: str) -> str:
    key = topic_key(topic)
    if key is None or key == "assistant":
        return capabilities(role)
    title, minimum, body = TOPICS[key]
    note = ""
    if RANK.get(role, 1) < RANK[minimum]:
        note = "\n\nЭти действия выполняет админ отдела или владелец. Смотреть данные вы можете."
    return f"### {title}\n\n{body}{note}"
